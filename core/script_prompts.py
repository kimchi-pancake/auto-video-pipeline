def random_topic_seed(rng=None, profile: str | None = None) -> str:
    """이번 영상의 필수 조건(카테고리·분야·접근 각도)을 무작위로 정해
    topic_idea_prompt에 넘길 문자열로 만듭니다."""
    import random
    r = rng or random
    # 카테고리는 무작위로 강제하지 않는다 — 소재와 안 맞는 카테고리(예: 김치 + 우주과학)를
    # 억지로 엮다가 이상한 대본이 나왔다. 카테고리는 모델이 소재에 맞게 고른다.
    if profile == PROFILE_WORLD_ECON:
        return (
            f"이번 영상의 대상은 반드시 '{r.choice(ECON_SEED_SETTINGS)}'이고, "
            f"접근 각도는 '{r.choice(ECON_SEED_OBJECTS)}'다. 이 대상에서 벗어나지 마라"
        )
    return (
        f"이번 영상의 주인공은 반드시 '{r.choice(SEED_SETTINGS)}'이고, "
        f"접근 각도는 '{r.choice(SEED_OBJECTS)}'다. 이 대상에서 벗어나지 마라"
    )


